// Regenerates src/ui/components/icons.generated.ts from the design handoff's
// 20 SVG icons. Strips C2PA metadata and keeps only geometry so the app ships
// no embedded provenance blobs. Run: node scripts/gen-icons.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = ".audit/design_handoff_lunchvoice_v2/icons";
const KEEP = new Set(["d", "cx", "cy", "r", "x", "y", "width", "height", "x1", "y1", "x2", "y2", "points", "rx"]);
const SHAPES = /<(path|circle|rect|line|polyline|polygon)\b([^>]*?)\/?>/g;
const ATTR = /([a-zA-Z-]+)="([^"]*)"/g;

const entries = [];
for (const file of readdirSync(DIR).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = readFileSync(join(DIR, file), "utf8").replace(/<metadata>[\s\S]*?<\/metadata>/g, "");
  const shapes = [];
  for (const [, tag, raw] of svg.matchAll(SHAPES)) {
    const attrs = {};
    for (const [, key, value] of raw.matchAll(ATTR)) if (KEEP.has(key)) attrs[key] = value;
    shapes.push({ tag, attrs });
  }
  entries.push(`  ${JSON.stringify(file.replace(/\.svg$/, ""))}: ${JSON.stringify(shapes)},`);
}

writeFileSync(
  "src/ui/components/icons.generated.ts",
  `// Generated by scripts/gen-icons.mjs from the design handoff icon set.
// 24px grid, 1.8 stroke, currentColor. Do not hand-edit.
export interface IconShape {
  tag: string;
  attrs: Record<string, string>;
}

export const HANDOFF_ICONS: Record<string, IconShape[]> = {
${entries.join("\n")}
};
`,
);
console.log(`wrote ${entries.length} icons`);
