-- 20260716140000_survey_tracking_integrity.sql
-- Closes two data-integrity gaps in the survey-response tracking path and
-- documents three currently-dead survey_answers columns.
--
-- 1. responses had no unique constraint on (session_id, student_id). The
--    submit_response RPC (0007_rpc_org_aware.sql) does a SELECT to check for
--    an existing response and then an INSERT — a check-then-insert race. A
--    double-tap on submit, a network retry, or two open tabs can insert two
--    response rows for the same student+session and double-award points.
--    session_members already has the equivalent guard via its composite
--    primary key; responses did not.
--
--    PRE-FLIGHT CHECK (required before this migration can apply cleanly):
--      select session_id, student_id, count(*)
--      from responses
--      group by session_id, student_id
--      having count(*) > 1;
--    This must return zero rows. If it does not, existing duplicate
--    responses must be reviewed and resolved by a human against real
--    production data before this constraint can be added — this migration
--    intentionally does not attempt dedup DML.
--
-- 2. sessions.join_code was declared globally unique across the whole table,
--    not scoped per org_id, even though the rest of this schema is
--    multi-tenant and org-scoped. As more orgs launch sessions, two
--    different orgs generating the same random 6-character join code (low
--    but nonzero odds — genCode() in ContentCentral.tsx draws 6 characters
--    from a 32-character alphabet) will hit a spurious insert failure.
--    join_session() and join_available_session() already filter by
--    org_id = ... and join_code = ... together, so no RPC logic changes are
--    required — only the constraint itself moves from unique(join_code) to
--    unique(org_id, join_code). The original constraint name is not known
--    ahead of time (auto-generated by Postgres in 0001_baseline.sql), so it
--    is looked up dynamically and dropped by discovered name.
--
-- 3. survey_answers.text_value, numeric_value, and option_values are
--    populated by submit_response() when present in p_answers, but the
--    client (src/routes/student/Survey.tsx submit()) only ever sends
--    {question_id, value} — these three columns are never populated by the
--    current product and nothing reads them back. Left in place (no
--    destructive schema change in this pass) but commented as reserved so
--    future readers do not assume they hold live data.

-- ============================================================
-- 1. responses: enforce one response per student per session
-- ============================================================

alter table public.responses
  add constraint responses_session_student_unique unique (session_id, student_id);

-- ============================================================
-- 2. sessions: re-scope join_code uniqueness to be per-org
-- ============================================================

do $$
declare
  v_conname text;
begin
  select con.conname
    into v_conname
  from pg_constraint con
  join pg_attribute att
    on att.attrelid = con.conrelid
   and att.attnum = any (con.conkey)
  where con.conrelid = 'public.sessions'::regclass
    and con.contype = 'u'
    and array_length(con.conkey, 1) = 1
    and att.attname = 'join_code';

  if v_conname is not null then
    execute format('alter table public.sessions drop constraint %I', v_conname);
  end if;
end
$$;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.sessions'::regclass
      and conname = 'sessions_org_join_code_unique'
  ) then
    alter table public.sessions
      add constraint sessions_org_join_code_unique unique (org_id, join_code);
  end if;
end
$$;

-- ============================================================
-- 3. survey_answers: document unpopulated/reserved columns
-- ============================================================

comment on column public.survey_answers.text_value is
  'Reserved, currently unpopulated: the client (src/routes/student/Survey.tsx submit()) only sends {question_id, value}. Do not assume this column holds live data.';

comment on column public.survey_answers.numeric_value is
  'Reserved, currently unpopulated: the client (src/routes/student/Survey.tsx submit()) only sends {question_id, value}. Do not assume this column holds live data.';

comment on column public.survey_answers.option_values is
  'Reserved, currently unpopulated: the client (src/routes/student/Survey.tsx submit()) only sends {question_id, value}. Do not assume this column holds live data.';
