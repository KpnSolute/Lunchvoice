// Emits types.ts from the contract's schemas (JSON Schema subset in src/lib.mjs). Deterministic output.

const HEADER = `// GENERATED by contract/build.mjs from the LunchVoice API contract. Do not edit.
// Source of truth: contract/src. Regenerate with: npm run contract:build
`;

function literal(value) {
  return JSON.stringify(value);
}

function paren(ts) {
  return ts.includes(" | ") || ts.includes(" & ") ? `(${ts})` : ts;
}

export function tsType(schema, indent = "") {
  if (schema.$ref) return schema.$ref.replace("#/components/schemas/", "");
  if (schema.oneOf) return schema.oneOf.map((s) => tsType(s, indent)).join(" | ");
  if ("const" in schema) return literal(schema.const);
  if (schema.enum) return schema.enum.map(literal).join(" | ");

  if (!schema.type) return "unknown";
  const types = Array.isArray(schema.type) ? schema.type : [schema.type];
  const parts = types.map((type) => {
    switch (type) {
      case "string":
        return "string";
      case "integer":
      case "number":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array":
        return `${paren(tsType(schema.items ?? {}, indent))}[]`;
      case "object": {
        const entries = Object.entries(schema.properties ?? {});
        if (entries.length === 0) return "Record<string, never>";
        const required = new Set(schema.required ?? []);
        const inner = `${indent}  `;
        const lines = entries.map(([key, value]) => `${inner}${/^[A-Za-z_][A-Za-z0-9_]*$/.test(key) ? key : literal(key)}${required.has(key) ? "" : "?"}: ${tsType(value, inner)};`);
        return `{\n${lines.join("\n")}\n${indent}}`;
      }
      default:
        return "unknown";
    }
  });
  return parts.join(" | ");
}

export function generateTypes(doc, operations) {
  const out = [HEADER];
  out.push("export type LvResult<T> = { ok: true; data: T; request_id: string } | LvFail;\n");
  for (const [name, schema] of Object.entries(doc.components.schemas)) {
    out.push(`export type ${name} = ${tsType(schema)};\n`);
  }
  const lines = ["export interface OperationMap {"];
  for (const op of operations) {
    const request = op.request ?? "undefined";
    const result = op.kind === "rpc-v2" ? `LvResult<${op.data}>` : op.success;
    lines.push(`  ${/^[A-Za-z_][A-Za-z0-9_]*$/.test(op.id) ? op.id : literal(op.id)}: { kind: ${literal(op.kind)}; status: ${literal(op.status)}; milestone: ${literal(op.milestone)}; path: ${literal(op.path)}; request: ${request}; result: ${result} };`);
  }
  lines.push("}\n");
  out.push(lines.join("\n"));
  out.push("export type OperationId = keyof OperationMap;\n");
  return out.join("\n");
}
